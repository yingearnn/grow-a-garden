app.use("/", mainRoutes);

//////////////////////////////////////////////////////
// SETUP ROUTES
//////////////////////////////////////////////////////


//////////////////////////////////////////////////////
// EXPORT APP
//////////////////////////////////////////////////////
module.exports = app;